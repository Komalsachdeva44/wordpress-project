// Enqueue scripts & styles
add_action('wp_enqueue_scripts', function () {
    wp_enqueue_script('ecwid-search-js', plugin_dir_url(__FILE__) . 'ecwid-search.js', ['jquery'], null, true);
    wp_localize_script('ecwid-search-js', 'ecwidSearch', [
        'ajaxUrl' => admin_url('admin-ajax.php'),
        'minChars'=> 3
    ]);
